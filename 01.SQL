--16. Using SH.CUSTOMERS, find the number of customers belonging to each marital status.
select cust_marital_status, count(*) as customer_count
from sh.CUSTOMERS
group by CUST_MARITAL_STATUS

--17. Using SH.CUSTOMERS, find the average customer year of birth for each gender.
select CUST_GENDER, AVG(Cust_year_of_birth) as AVG_Cust_year_of_birth
from sh.customers
group by CUST_GENDER

--18. Using SH.PRODUCTS, find the average list price of products in each product category.
select PROD_CATEGORY, avg(PROD_LIST_PRICE) as AVG_Prod_list_price
from sh.PRODUCTS
group by prod_category

--19. Using SH.PRODUCTS, find the highest minimum price in each product subcategory.
select prod_subcategory, Max(PROD_MIN_PRICE) as High_Prod_Min_price
from sh.PRODUCTS
group by prod_subcategory

--20. Using SH.SALES, calculate the total sales amount generated by each channel.
select CHANNEL_ID, sum(AMOUNT_SOLD) as Total_sales
from sh.SALES
group by channel_id

--21. Using SH.SALES, calculate the total quantity sold for each product.
select PROD_ID, sum(QUANTITY_SOLD) as Total_Quantity
from sh.SALES
group by prod_id

--22. Using SH.SALES, find the average sales amount for each promotion.
select PROMO_ID, avg(AMOUNT_SOLD) as AVG_Sales_Amount
from sh.SALES
group by promo_id

--23. Using SH.PROMOTIONS, calculate the total promotion cost for each promotion category.
select PROMO_CATEGORY, sum(PROMO_COST) as Total_Promo_Cost
from sh.PROMOTIONS
group by promo_category

--24. Using SH.COUNTRIES, count the number of countries belonging to each region.
select COUNTRY_REGION, count(COUNTRY_NAME) as Number_of_countries
from sh.COUNTRIES
group by country_region

--25. Using SH.COSTS, calculate the average unit cost for each product.
select PROD_ID, avg(UNIT_COST) as Avg_Unit_Cost
from sh.COSTS
group by PROD_ID 

